#!/usr/bin/env luajit
-- import-drops.lua -- generate src/domain/drops/data.fnl (item-id -> drop entry)
-- from vendor/bis-source/item-sources.lua, scoped to the items actually in the
-- generated BiS catalog. Run via `task import-drops`.
--
-- Drop categories -> entry:
--   Boss/Rare/Zone Drop -> :base-drop-p = dropChance, :source-activity = zone slug
--                          (or :unknown when the source has no zone)
--   Vendor              -> :source-activity :vendor, :base-drop-p 1.0
--   Quest               -> :source-activity :quest,  :base-drop-p 1.0
--   anything else / no dropChance on a drop -> omitted (counted)
-- :ml-pool is left unset (Phase 4 / OQ-3). Output is sorted by item id.

local SRC = "vendor/bis-source"
local OUT = "src/domain/drops"

dofile(SRC .. "/item-sources.lua")  -- BIS_ITEM_SOURCES

-- Item IDs present in the generated catalog (src/domain/bis/*.fnl).
local function catalog_ids()
  local ids, p = {}, assert(io.popen("grep -ohE ':item \\{:id [0-9]+' src/domain/bis/*.fnl"))
  for line in p:lines() do
    local id = line:match("(%d+)")
    if id then ids[tonumber(id)] = true end
  end
  p:close()
  return ids
end

local function slug(name)
  return (name:gsub("'", ""):lower():gsub("[^%w]+", "-")
              :gsub("^%-", ""):gsub("%-$", ""))
end

local DROP_CAT = {["Boss Drop"] = true, ["Rare Drop"] = true, ["Zone Drop"] = true}

-- Build entries.
local ids = catalog_ids()
local entries = {}
local skipped = {no_source = 0, drop_no_chance = 0, other_cat = 0}
for id in pairs(ids) do
  local s = BIS_ITEM_SOURCES[id]
  if not s then
    skipped.no_source = skipped.no_source + 1
  elseif DROP_CAT[s.category] then
    if s.dropChance then
      entries[id] = {
        activity = s.zone and slug(s.zone) or "unknown",
        p = s.dropChance, boss = s.boss, zone = s.zone,
      }
    else
      skipped.drop_no_chance = skipped.drop_no_chance + 1
    end
  elseif s.category == "Vendor" then
    entries[id] = {activity = "vendor", p = 1.0, boss = s.boss, zone = s.zone}
  elseif s.category == "Quest" then
    entries[id] = {activity = "quest", p = 1.0, boss = s.boss, zone = s.zone}
  else
    skipped.other_cat = skipped.other_cat + 1
  end
end

-- Emit a single sorted map literal.
local order = {}; for id in pairs(entries) do order[#order + 1] = id end
table.sort(order)
local function kw(s) return ":" .. s end
local function field(k, v) return v and (" " .. k .. " " .. v) or "" end
local lines = {}
for _, id in ipairs(order) do
  local e = entries[id]
  local boss = e.boss and (" :boss " .. string.format("%q", e.boss)) or ""
  local zone = e.zone and (" :zone " .. string.format("%q", e.zone)) or ""
  lines[#lines + 1] = string.format(
    " %d {:item-id %d :source-activity %s :base-drop-p %s%s%s}",
    id, id, kw(e.activity), tostring(e.p), boss, zone)
end

os.execute("mkdir -p " .. OUT)
local body = string.format([[
;; src/domain/drops/data.fnl -- GENERATED by scripts/import-drops.lua. DO NOT EDIT.
;; Source: nexus-devs/wow-classic-items (MIT) via vendor/bis-source/item-sources.lua.
;; See vendor/bis-source/README.md. Regenerate: task vendor-bis-source && task import-drops.
;;
;; Pure data: item-id -> DropEntry map, registered for src/domain/drop-table.fnl
;; to read and validate. No WoW API.

(local Routina (or _G.Routina {}))
(set _G.Routina Routina)

(local drop-data
       {%s})

(set Routina.drop-data drop-data)

drop-data
]], table.concat(lines, "\n"))
local f = assert(io.open(OUT .. "/data.fnl", "w"))
f:write(body)
f:close()

print(string.format(
  "drop-table: %d entries  (catalog ids=%d)  skipped: no-source=%d drop-no-chance=%d other=%d",
  #order, (function() local n = 0 for _ in pairs(ids) do n = n + 1 end return n end)(),
  skipped.no_source, skipped.drop_no_chance, skipped.other_cat))
