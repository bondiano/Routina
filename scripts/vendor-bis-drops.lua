#!/usr/bin/env luajit
-- vendor-bis-drops.lua -- derive vendor/bis-source/item-sources.lua (id -> drop
-- source) for the item IDs in vendor/bis-source/bis_data.lua, from the
-- nexus-devs/wow-classic-items dataset (MIT). Run by `task vendor-bis-source`.
-- Usage: luajit scripts/vendor-bis-drops.lua <data.json> <zones.json>
--
-- Per item we keep one source: the highest-dropChance source object if any,
-- else the first. Zone ids are resolved to names via zones.json at vendor time
-- so the importer needs only this one table.

local data_path = assert(arg[1], "usage: vendor-bis-drops.lua <data.json> <zones.json>")
local zones_path = assert(arg[2], "usage: vendor-bis-drops.lua <data.json> <zones.json>")

local function unescape(s)
  return (s:gsub("&apos;", "'"):gsub("&quot;", '"'):gsub("&lt;", "<")
           :gsub("&gt;", ">"):gsub("&amp;", "&"))
end

-- 1. needed BiS item IDs
local need = {}
for line in io.lines("vendor/bis-source/bis_data.lua") do
  local id = line:match("ItemId%s*=%s*(%d+)")
  if id then need[tonumber(id)] = true end
end

-- 2. zone id -> name (from zones.json)
local zf = assert(io.open(zones_path, "r"))
local zblob = zf:read("*a"); zf:close()
local zone_name = {}
for zid, name in zblob:gmatch('"id":(%d+),"name":"(.-)"') do
  zone_name[tonumber(zid)] = unescape(name)
end

-- 3. for each needed item, scope a window to its object and pick a source
local df = assert(io.open(data_path, "r"))
local blob = df:read("*a"); df:close()

-- Parse one source object's fields.
local function parse_source(obj)
  return {
    category = obj:match('"category":"(.-)"'),
    name = obj:match('"name":"(.-)"'),
    zone = tonumber(obj:match('"zone":(%d+)')),
    dropChance = tonumber(obj:match('"dropChance":([0-9.]+)')),
  }
end

-- Choose the best source object inside a `"source":` value (object or array):
-- highest dropChance, else the first object seen.
local function best_source(window)
  local val = window:match('"source":(%b{})') or window:match('"source":(%b%[%])')
  if not val then return nil end
  local best, best_first
  for obj in val:gmatch("(%b{})") do
    local s = parse_source(obj)
    if not best_first then best_first = s end
    if s.dropChance and (not best or s.dropChance > best.dropChance) then
      best = s
    end
  end
  return best or best_first
end

local sources = {}
local found, missing = 0, 0
for id in pairs(need) do
  local anchor = '"itemId":' .. id .. ","
  local s = blob:find(anchor, 1, true)
  if s then
    local window = blob:sub(s, s + 4000)
    local nxt = window:find('"itemId":', #anchor + 1, true)
    if nxt then window = window:sub(1, nxt - 1) end
    local src = best_source(window)
    if src and src.category then
      sources[id] = src
      found = found + 1
    else
      missing = missing + 1
    end
  else
    missing = missing + 1
  end
end

-- 4. emit, sorted by id for stable diffs
local ids = {}; for id in pairs(sources) do ids[#ids + 1] = id end
table.sort(ids)
local out = assert(io.open("vendor/bis-source/item-sources.lua", "w"))
out:write("-- GENERATED by scripts/vendor-bis-drops.lua. Do not edit.\n")
out:write("-- id -> {category, boss, zone (name), dropChance} for BiS item IDs.\n")
out:write("-- Source: nexus-devs/wow-classic-items (MIT), data/json/{data,zones}.json.\n")
out:write("BIS_ITEM_SOURCES = {}\n")
local function q(s) return s and string.format("%q", unescape(s)) or "nil" end
for _, id in ipairs(ids) do
  local s = sources[id]
  local zname = s.zone and zone_name[s.zone] or nil
  out:write(string.format(
    "BIS_ITEM_SOURCES[%d] = {category = %s, boss = %s, zone = %s, dropChance = %s}\n",
    id, q(s.category), q(s.name), q(zname),
    s.dropChance and tostring(s.dropChance) or "nil"))
end
out:close()
print(string.format("item-sources.lua: ids=%d with-source=%d no-source=%d",
  found + missing, found, missing))
