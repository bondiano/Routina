#!/usr/bin/env luajit
-- vendor-yield-bosses.lua -- derive vendor/bis-source/zone-bosses.lua (zone
-- name -> sorted distinct boss names) from the nexus-devs/wow-classic-items
-- dataset (MIT). Run by `task vendor-bis-source`, consumed by
-- scripts/import-yields.lua to derive deterministic badge counts (heroic
-- bosses x 1 Badge of Justice).
-- Usage: luajit scripts/vendor-yield-bosses.lua <data.json> <zones.json>
--
-- Scans EVERY item's source objects (not just BiS items): a zone's boss list
-- is the distinct "Boss Drop" source names seen anywhere in the dataset. The
-- itemization is boss-complete for instanced zones, so this approximates the
-- real boss roster; scripts/yields-curated.lua can override the count where
-- the dataset disagrees with the live client.

local data_path = assert(arg[1], "usage: vendor-yield-bosses.lua <data.json> <zones.json>")
local zones_path = assert(arg[2], "usage: vendor-yield-bosses.lua <data.json> <zones.json>")

local function unescape(s)
  return (s:gsub("&apos;", "'"):gsub("&quot;", '"'):gsub("&lt;", "<")
           :gsub("&gt;", ">"):gsub("&amp;", "&"))
end

-- 1. zone id -> name (from zones.json)
local zf = assert(io.open(zones_path, "r"))
local zblob = zf:read("*a"); zf:close()
local zone_name = {}
for zid, name in zblob:gmatch('"id":(%d+),"name":"(.-)"') do
  zone_name[tonumber(zid)] = unescape(name)
end

-- 2. distinct (zone, boss) pairs across all "Boss Drop" source objects
local df = assert(io.open(data_path, "r"))
local blob = df:read("*a"); df:close()

local bosses = {}  -- zone name -> {boss name -> true}
local function collect(obj)
  local category = obj:match('"category":"(.-)"')
  if category ~= "Boss Drop" then return end
  local name = obj:match('"name":"(.-)"')
  local zid = tonumber(obj:match('"zone":(%d+)'))
  local zone = zid and zone_name[zid]
  if name and zone then
    bosses[zone] = bosses[zone] or {}
    bosses[zone][unescape(name)] = true
  end
end

for val in blob:gmatch('"source":(%b{})') do
  collect(val)
end
for arr in blob:gmatch('"source":(%b[])') do
  for obj in arr:gmatch("(%b{})") do
    collect(obj)
  end
end

-- 3. emit sorted zone -> sorted boss list
local zones = {}
for z in pairs(bosses) do zones[#zones + 1] = z end
table.sort(zones)

local lines = {}
for _, z in ipairs(zones) do
  local names = {}
  for b in pairs(bosses[z]) do names[#names + 1] = b end
  table.sort(names)
  for i, b in ipairs(names) do names[i] = string.format("%q", b) end
  lines[#lines + 1] = string.format("ZONE_BOSSES[%q] = {%s}", z,
                                    table.concat(names, ", "))
end

local f = assert(io.open("vendor/bis-source/zone-bosses.lua", "w"))
f:write([[
-- GENERATED by scripts/vendor-yield-bosses.lua. Do not edit.
-- zone name -> sorted distinct boss names (category "Boss Drop").
-- Source: nexus-devs/wow-classic-items (MIT), data/json/{data,zones}.json.
ZONE_BOSSES = {}
]] .. table.concat(lines, "\n") .. "\n")
f:close()

print(string.format("zone-bosses: %d zones", #zones))
