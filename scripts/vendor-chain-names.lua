#!/usr/bin/env luajit
-- vendor-chain-names.lua -- derive vendor/chain-source/quest-names.lua
-- (quest-id -> name) for the quest IDs referenced in
-- vendor/chain-source/AttuneData.lua, sourced from Questie's TBC quest DB
-- (no upstream license -- risk accepted 2026-06-05, see CREDITS.md; the
-- extracted pairs are factual Blizzard quest titles). Run by
-- `task vendor-chain-source`.
-- Usage: luajit scripts/vendor-chain-names.lua <path-to-tbcQuestDB.lua>

local db_path = assert(arg[1], "usage: vendor-chain-names.lua <tbcQuestDB.lua>")

-- 1. collect needed quest IDs from the vendored Attune steps (the quest-ish
--    step types carry a wowhead quest id in ID_WOWHEAD)
local QUESTISH = {["Quest"] = true, ["Pick Up"] = true, ["Turn In"] = true}
local need = {}
for line in io.lines("vendor/chain-source/AttuneData.lua") do
  local t, id = line:match('TYPE="([^"]+)".-ID_WOWHEAD="(%d+)"')
  if t and QUESTISH[t] then need[tonumber(id)] = true end
end
need[0] = nil
local ncount = 0; for _ in pairs(need) do ncount = ncount + 1 end

-- 2. scan Questie's questData payload for [id] = {"Name", ... (the name is
--    questKeys index 1; streaming line match, no loadstring of the 1.6MB blob)
local names = {}
for line in io.lines(db_path) do
  local id, name = line:match('^%[(%d+)%] = {"(.-)",')
  if id then
    id = tonumber(id)
    if need[id] and not names[id] then names[id] = name end
  end
end

-- 3. emit a stable, sorted Lua table
local ids = {}; for id in pairs(need) do ids[#ids + 1] = id end
table.sort(ids)
local out = assert(io.open("vendor/chain-source/quest-names.lua", "w"))
out:write("-- GENERATED by scripts/vendor-chain-names.lua. Do not edit.\n")
out:write("-- quest-id -> quest title, filtered to the quest IDs in AttuneData.lua.\n")
out:write("-- Source: Questie/Questie Database/TBC/tbcQuestDB.lua (unlicensed;\n")
out:write("-- risk accepted -- see CREDITS.md). Titles are factual Blizzard strings.\n")
out:write("CHAIN_QUEST_NAMES = {}\n")
local found = 0
for _, id in ipairs(ids) do
  if names[id] then
    found = found + 1
    out:write(string.format("CHAIN_QUEST_NAMES[%d] = %q\n", id, names[id]))
  end
end
out:close()
print(string.format("quest-names.lua: needed=%d resolved=%d missing=%d",
  ncount, found, ncount - found))
