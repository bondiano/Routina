#!/usr/bin/env luajit
-- vendor-bis-names.lua -- derive vendor/bis-source/item-names.lua (id -> name)
-- for the item IDs referenced in vendor/bis-source/bis_data.lua, sourced from the
-- nexus-devs/wow-classic-items dataset (MIT). Run by `task vendor-bis-source`.
-- Usage: luajit scripts/vendor-bis-names.lua <path-to-nexus-data.json>

local json_path = assert(arg[1], "usage: vendor-bis-names.lua <data.json>")

local function unescape(s)
  return (s:gsub("&apos;", "'"):gsub("&quot;", '"'):gsub("&lt;", "<")
           :gsub("&gt;", ">"):gsub("&amp;", "&"))
end

-- 1. collect needed IDs from the vendored BiS links
local need = {}
for line in io.lines("vendor/bis-source/bis_data.lua") do
  local id = line:match("ItemId%s*=%s*(%d+)")
  if id then need[tonumber(id)] = true end
end
local ncount = 0; for _ in pairs(need) do ncount = ncount + 1 end

-- 2. scan the dataset for id -> name (streaming gmatch; no JSON lib needed)
local f = assert(io.open(json_path, "r"))
local blob = f:read("*a"); f:close()
local names = {}
for id, name in blob:gmatch('"itemId":(%d+),"name":"(.-)"') do
  id = tonumber(id)
  if need[id] and not names[id] then names[id] = unescape(name) end
end

-- 3. emit a stable, sorted Lua table
local ids = {}; for id in pairs(need) do ids[#ids + 1] = id end
table.sort(ids)
local out = assert(io.open("vendor/bis-source/item-names.lua", "w"))
out:write("-- GENERATED by scripts/vendor-bis-names.lua. Do not edit.\n")
out:write("-- id -> item name, filtered to the BiS item IDs in bis_data.lua.\n")
out:write("-- Source: nexus-devs/wow-classic-items (MIT), data/json/data.json.\n")
out:write("BIS_ITEM_NAMES = {}\n")
local found = 0
for _, id in ipairs(ids) do
  if names[id] then
    found = found + 1
    out:write(string.format("BIS_ITEM_NAMES[%d] = %q\n", id, names[id]))
  end
end
out:close()
print(string.format("item-names.lua: needed=%d resolved=%d missing=%d",
  ncount, found, ncount - found))
