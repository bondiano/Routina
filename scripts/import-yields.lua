#!/usr/bin/env luajit
-- import-yields.lua -- generate src/domain/yields/data.fnl (activity-id ->
-- ActivityYield) from scripts/yields-curated.lua (hand-curated gold bands,
-- badge overrides) + vendor/bis-source/zone-bosses.lua (derived boss rosters
-- for deterministic badge counts). Run via `task import-yields`.
--
-- badges = "bosses" in the curated table -> #ZONE_BOSSES[zone]; a number is
-- taken verbatim. Cross-checks curated keys against the activities.fnl
-- registry: a curated id missing from the registry (or vice versa) fails the
-- import so the two never drift apart silently.

local SRC = "vendor/bis-source"
local OUT = "src/domain/yields"

dofile(SRC .. "/zone-bosses.lua") -- ZONE_BOSSES
local curated = dofile("scripts/yields-curated.lua")

-- Registry ids from src/domain/activities.fnl (`{:id :slug` rows).
local function registry_ids()
  local ids, p = {}, assert(io.popen("grep -ohE '\\{:id :[a-z-]+' src/domain/activities.fnl"))
  for line in p:lines() do
    local id = line:match(":id :([%a-]+)")
    if id then ids[id] = true end
  end
  p:close()
  return ids
end

-- Cross-check: curated and registry must cover the same id set.
local ids = registry_ids()
for id in pairs(curated) do
  assert(ids[id], "yields-curated has unknown activity id: " .. id)
end
for id in pairs(ids) do
  assert(curated[id], "activities registry id missing from yields-curated: " .. id)
end

-- Build + emit sorted by activity id.
local order = {}
for id in pairs(curated) do order[#order + 1] = id end
table.sort(order)

local lines = {}
for _, id in ipairs(order) do
  local c = curated[id]
  local badges = c.badges
  if badges == "bosses" then
    local roster = ZONE_BOSSES[c.zone]
    assert(roster and #roster > 0,
           "no boss roster for zone '" .. tostring(c.zone) .. "' (" .. id .. ")")
    badges = #roster
  end
  assert(type(badges) == "number", "bad badges for " .. id)
  assert(type(c.gold) == "table" and c.gold[1] and c.gold[2] and c.gold[1] <= c.gold[2],
         "bad gold band for " .. id)
  local rep = ""
  if c.rep then
    rep = string.format(" :rep {:faction :%s :amount %d}", c.rep.faction, c.rep.amount)
  end
  lines[#lines + 1] = string.format(
    " :%s {:activity-id :%s :badges %d :gold-min %d :gold-max %d%s}",
    id, id, badges, c.gold[1], c.gold[2], rep)
end

os.execute("mkdir -p " .. OUT)
local body = string.format([[
;; src/domain/yields/data.fnl -- GENERATED by scripts/import-yields.lua. DO NOT EDIT.
;; Curated bands: scripts/yields-curated.lua (this repo). Badge counts derived
;; from nexus-devs/wow-classic-items (MIT) via vendor/bis-source/zone-bosses.lua.
;; Routina aggregate licensed GPL-3.0 (see root LICENSE).
;; Regenerate: task vendor-bis-source && task import-yields.
;;
;; Pure data: activity-id -> ActivityYield map, registered for
;; src/domain/yields.fnl to read and validate. Gold is COPPER per clear, an
;; honest band (OQ-12); badges are deterministic per clear. No WoW API.

(local Routina (or _G.Routina {}))
(set _G.Routina Routina)

(local yields-data
       {%s})

(set Routina.yields-data yields-data)

yields-data
]], table.concat(lines, "\n"))
local f = assert(io.open(OUT .. "/data.fnl", "w"))
f:write(body)
f:close()

print(string.format("yields: %d activities", #order))
